CREATE OR REPLACE FUNCTION "public"."handle_new_auth_user"() RETURNS "trigger"
    LANGUAGE "plpgsql" SECURITY DEFINER
    AS $$declare
  raw_data jsonb := new.raw_user_meta_data;
begin
  insert into public.users (
    id,
    email,
    username,
    first_name,
    last_name,
    title,
    birthday,
    offer_code,
    country,
    position,
    customer_id,
    plan_id,
    subscription_id,
    subscription_status,
    current_period_end,
    trial_end,
    created_at
  )
  values (
    new.id,
    new.email,
    raw_data ->> 'username',
    raw_data ->> 'first_name',
    raw_data ->> 'last_name',
    raw_data ->> 'title',
    CASE
      WHEN raw_data ->> 'birthday' IS NULL OR raw_data ->> 'birthday' = ''
      THEN NULL
      ELSE to_date(raw_data ->> 'birthday', 'DD/MM/YYYY')
    END,
    raw_data ->> 'offer_code',
    raw_data ->> 'country',
    raw_data ->> 'position',
    raw_data ->> 'customer_id',
    raw_data ->> 'plan_id',
    raw_data ->> 'subscription_id',
    COALESCE(raw_data->>'subscription_status', 'PRO'),
    (raw_data->>'current_period_end')::timestamptz,
    (raw_data->>'trial_end')::timestamptz,
    NOW()
  );

  RETURN NEW;
end;$$;


ALTER FUNCTION "public"."handle_new_auth_user"() OWNER TO "postgres";


