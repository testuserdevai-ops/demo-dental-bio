-- Create blocked_email_domains table to prevent registration from disposable/temp email providers
CREATE TABLE IF NOT EXISTS public.blocked_email_domains (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain TEXT NOT NULL UNIQUE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Enable RLS
ALTER TABLE public.blocked_email_domains ENABLE ROW LEVEL SECURITY;

-- Allow all authenticated users (and anon for registration) to read blocked domains
CREATE POLICY "Anyone can read blocked domains"
    ON public.blocked_email_domains
    FOR SELECT
    USING (true);

-- Only service_role can insert/update/delete (managed via admin dashboard or API)
-- No INSERT/UPDATE/DELETE policies for anon/authenticated = denied by default with RLS

