-- ============================================================
-- Security logs — records all blocked/malicious activity
-- ============================================================

CREATE TABLE IF NOT EXISTS public.security_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_type TEXT NOT NULL,        -- 'blocked_domain', 'blocked_fingerprint', 'blocked_ip'
    email TEXT,
    username TEXT,
    first_name TEXT,
    last_name TEXT,
    ip_address TEXT,
    user_agent TEXT,
    fingerprint TEXT,
    country TEXT,
    location TEXT,
    route TEXT,
    details JSONB,                   -- extra context (e.g. blocked domain name, reason)
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- RLS enabled with NO public policies — only service_role can read/write
ALTER TABLE public.security_logs ENABLE ROW LEVEL SECURITY;

CREATE INDEX IF NOT EXISTS idx_security_logs_event_type ON public.security_logs (event_type);
CREATE INDEX IF NOT EXISTS idx_security_logs_created_at ON public.security_logs (created_at DESC);
CREATE INDEX IF NOT EXISTS idx_security_logs_email ON public.security_logs (email);
CREATE INDEX IF NOT EXISTS idx_security_logs_ip_address ON public.security_logs (ip_address);
