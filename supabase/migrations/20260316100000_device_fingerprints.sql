-- Junction table: many-to-many between users and device fingerprints
-- One user can have multiple devices, one device can be used by multiple accounts
CREATE TABLE IF NOT EXISTS public.user_device_fingerprints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
    fingerprint TEXT NOT NULL,
    last_seen_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    UNIQUE(user_id, fingerprint)
);

-- Enable RLS
ALTER TABLE public.user_device_fingerprints ENABLE ROW LEVEL SECURITY;

-- Allow reading (needed for admin dashboard)
CREATE POLICY "Anyone can read user device fingerprints"
    ON public.user_device_fingerprints
    FOR SELECT
    USING (true);

-- Indexes for fast lookups in both directions
CREATE INDEX IF NOT EXISTS idx_user_device_fingerprints_user_id ON public.user_device_fingerprints (user_id);
CREATE INDEX IF NOT EXISTS idx_user_device_fingerprints_fingerprint ON public.user_device_fingerprints (fingerprint);

-- Create blocked_fingerprints table for admin-managed device blocking
CREATE TABLE IF NOT EXISTS public.blocked_fingerprints (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    fingerprint TEXT NOT NULL UNIQUE,
    reason TEXT,
    blocked_by UUID REFERENCES auth.users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Enable RLS
ALTER TABLE public.blocked_fingerprints ENABLE ROW LEVEL SECURITY;

-- Allow reading blocked fingerprints (needed for registration/login checks)
CREATE POLICY "Anyone can read blocked fingerprints"
    ON public.blocked_fingerprints
    FOR SELECT
    USING (true);

-- Only service_role can insert/update/delete (managed via admin API)
-- No INSERT/UPDATE/DELETE policies for anon/authenticated = denied by default with RLS

-- Create index for fast fingerprint lookups
CREATE INDEX IF NOT EXISTS idx_blocked_fingerprints_fingerprint ON public.blocked_fingerprints (fingerprint);
