-- ============================================================
-- Profile audit log
--
-- A single, generic audit table that captures every INSERT/UPDATE/DELETE
-- on profile-related tables (users, dentistries, socials, link_groups,
-- links, dentistry_links, galleries, general_galleries, reviews).
--
-- The actual triggers are attached to each table in follow-up migrations.
-- This migration only sets up the storage + the generic trigger function.
-- ============================================================

CREATE TABLE IF NOT EXISTS public.profile_audit_log (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       UUID NOT NULL,                 -- profile owner (subject)
    actor_id      UUID,                          -- auth.uid() at time of change
    actor_role    TEXT,                          -- 'self' | 'admin' | 'system'
    table_name    TEXT NOT NULL,
    record_id     TEXT NOT NULL,                 -- PK of the changed row, as text
    operation     TEXT NOT NULL CHECK (operation IN ('INSERT','UPDATE','DELETE')),
    changed_keys  TEXT[] NOT NULL DEFAULT '{}',  -- only fields that actually differ
    old_values    JSONB,                         -- null on INSERT
    new_values    JSONB,                         -- null on DELETE
    ip_address    TEXT,
    user_agent    TEXT,
    created_at    TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW()
);

ALTER TABLE public.profile_audit_log ENABLE ROW LEVEL SECURITY;

-- Owners can read their own audit entries. No INSERT/UPDATE/DELETE policy:
-- only the SECURITY DEFINER trigger function (running as table owner) writes.
CREATE POLICY "profile_audit_log_select_own"
    ON public.profile_audit_log
    FOR SELECT
    TO authenticated
    USING (user_id = auth.uid());

CREATE INDEX IF NOT EXISTS idx_profile_audit_log_user_id_created_at
    ON public.profile_audit_log (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS idx_profile_audit_log_table_op
    ON public.profile_audit_log (table_name, operation);
CREATE INDEX IF NOT EXISTS idx_profile_audit_log_actor_id
    ON public.profile_audit_log (actor_id);
CREATE INDEX IF NOT EXISTS idx_profile_audit_log_changed_keys
    ON public.profile_audit_log USING GIN (changed_keys);

-- ============================================================
-- Generic trigger function
--
-- Usage:
--   CREATE TRIGGER trg_audit_<table> AFTER INSERT OR UPDATE OR DELETE
--   ON <table>
--   FOR EACH ROW EXECUTE FUNCTION public.fn_audit_profile_change(
--       '<user_id_column>',  -- column on this table that holds the profile owner's user id
--       '<pk_column>'        -- column on this table that holds the row's primary key
--   );
--
-- For tables where user_id must be resolved via a join (socials, links,
-- link_groups, dentistry_links), use a per-table wrapper trigger function
-- introduced in a later migration instead of this generic one.
-- ============================================================

CREATE OR REPLACE FUNCTION public.fn_audit_profile_change()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
    v_user_id  UUID;
    v_actor    UUID := auth.uid();
    v_old      JSONB := CASE WHEN TG_OP = 'INSERT' THEN NULL ELSE to_jsonb(OLD) END;
    v_new      JSONB := CASE WHEN TG_OP = 'DELETE' THEN NULL ELSE to_jsonb(NEW) END;
    v_keys     TEXT[] := '{}';
    v_pk       TEXT;
    v_user_col TEXT := TG_ARGV[0];
    v_pk_col   TEXT := TG_ARGV[1];
    v_headers  JSONB;
    v_ip       TEXT;
    v_ua       TEXT;

    -- Fields excluded from changed_keys diffing.
    -- click_counter floods on every public link click; updated_at is bookkeeping noise.
    v_ignored  TEXT[] := ARRAY['updated_at', 'click_counter'];
BEGIN
    v_user_id := COALESCE(
        (v_new ->> v_user_col)::UUID,
        (v_old ->> v_user_col)::UUID
    );
    v_pk := COALESCE(v_new ->> v_pk_col, v_old ->> v_pk_col);

    BEGIN
        v_headers := NULLIF(current_setting('request.headers', true), '')::JSONB;
        v_ip := v_headers ->> 'x-client-ip';
        v_ua := v_headers ->> 'x-client-ua';
    EXCEPTION WHEN OTHERS THEN
        v_ip := NULL;
        v_ua := NULL;
    END;

    IF TG_OP = 'UPDATE' THEN
        SELECT COALESCE(array_agg(key), '{}')
        INTO v_keys
        FROM jsonb_each(v_new) AS e(key, value)
        WHERE v_new -> key IS DISTINCT FROM v_old -> key
          AND key <> ALL (v_ignored);

        -- Nothing meaningful changed (e.g. only click_counter ticked) — skip the row.
        IF array_length(v_keys, 1) IS NULL THEN
            RETURN NEW;
        END IF;
    END IF;

    INSERT INTO public.profile_audit_log
        (user_id, actor_id, actor_role, table_name, record_id,
         operation, changed_keys, old_values, new_values,
         ip_address, user_agent)
    VALUES
        (v_user_id,
         v_actor,
         CASE
             WHEN v_actor IS NULL THEN 'system'
             WHEN v_actor = v_user_id THEN 'self'
             ELSE 'admin'
         END,
         TG_TABLE_NAME,
         v_pk,
         TG_OP,
         COALESCE(v_keys, '{}'),
         v_old,
         v_new,
         v_ip,
         v_ua);

    RETURN COALESCE(NEW, OLD);
END;
$$;

COMMENT ON FUNCTION public.fn_audit_profile_change() IS
    'Generic AFTER trigger that records mutations into profile_audit_log. '
    'TG_ARGV[0]=user_id column, TG_ARGV[1]=pk column. '
    'Ignores changes to updated_at and click_counter.';
